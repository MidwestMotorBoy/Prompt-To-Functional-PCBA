#!/usr/bin/env python3
"""make.py : build the Monolith sheets from code, prove they are electrically identical to the frozen netlist, render them.

Run from anywhere:  python make.py
Output: out/sheets/*.kicad_sch, out/render/sheets.pdf, out/render/page-N.png (100 dpi).
Exit code 1 if the netlist differs. Do not edit this file.

KiCad 10's kicad-cli is found in this order: env KICAD_CLI, kicad-cli on PATH, the default Windows / macOS / Linux
install paths, and finally Docker (image kicad/kicad:10.0). PNG rendering uses PyMuPDF (pip install pymupdf),
or pdftoppm if PyMuPDF is missing.
"""
import os, sys, shutil, subprocess, glob

W = os.path.dirname(os.path.abspath(__file__))
PY = sys.executable
SH = os.path.join(W, "shared")
OUT = os.path.join(W, "out")
SHEETS = os.path.join(OUT, "sheets")
RENDER = os.path.join(OUT, "render")

def run(cmd, cwd=W, env=None, tail=None):
    r = subprocess.run(cmd, cwd=cwd, env=env, capture_output=True, text=True)
    text = (r.stdout or "") + (r.stderr or "")
    lines = [l for l in text.splitlines() if l.strip()]
    for l in (lines[-tail:] if tail else lines):
        print(l)
    if r.returncode != 0:
        print(f"FAILED ({r.returncode}): {' '.join(cmd)}")
        sys.exit(1)
    return text

def find_kicad_cli():
    c = os.environ.get("KICAD_CLI")
    if c and os.path.exists(c):
        return [c]
    c = shutil.which("kicad-cli")
    if c:
        return [c]
    for c in [r"C:\Program Files\KiCad\10.0\bin\kicad-cli.exe",
              "/Applications/KiCad/KiCad.app/Contents/MacOS/kicad-cli",
              "/usr/bin/kicad-cli", "/usr/local/bin/kicad-cli"]:
        if os.path.exists(c):
            return [c]
    return None

def kicad(args):
    """Run kicad-cli with paths relative to out/sheets."""
    cli = find_kicad_cli()
    if cli:
        return run(cli + args, cwd=SHEETS)
    docker = shutil.which("docker")
    if not docker:
        print("kicad-cli not found (install KiCad 10 or set KICAD_CLI) and docker is not available")
        sys.exit(1)
    pre = ["sudo"] if os.name != "nt" and os.geteuid() != 0 and subprocess.run(
        [docker, "ps"], capture_output=True).returncode != 0 else []
    return run(pre + [docker, "run", "--rm", "-u", "0", "-v", f"{SHEETS}:/w", "-w", "/w",
                      "kicad/kicad:10.0", "kicad-cli"] + args, cwd=SHEETS)

def render(pdf):
    for f in glob.glob(os.path.join(RENDER, "page-*.png")):
        os.remove(f)
    try:
        try:
            import pymupdf as fitz
        except ImportError:
            import fitz  # older PyMuPDF
        doc = fitz.open(pdf)
        for i, page in enumerate(doc, 1):
            page.get_pixmap(dpi=100).save(os.path.join(RENDER, f"page-{i}.png"))
        return
    except ImportError:
        pass
    if shutil.which("pdftoppm"):
        run(["pdftoppm", "-r", "100", "-png", pdf, os.path.join(RENDER, "page")])
        for f in glob.glob(os.path.join(RENDER, "page-0*.png")):   # pdftoppm may zero-pad
            os.rename(f, os.path.join(RENDER, "page-" + os.path.basename(f)[5:].lstrip("0")))
        return
    print("No PNG renderer: pip install pymupdf"); sys.exit(1)

def main():
    env = dict(os.environ, SYMBOL_DIRS=os.path.join(SH, "symbols"))
    shutil.rmtree(OUT, ignore_errors=True)
    os.makedirs(RENDER)
    design = os.path.join(W, "design")
    run([PY, "top.py", OUT], cwd=design, env=env, tail=0)
    # the code itself must not change the circuit
    run([PY, os.path.join(W, "tools", "compare.py"), os.path.join(SH, "frozen_netlist.json"),
         os.path.join(OUT, "netlist.json")], tail=2)
    run([PY, "draw.py", OUT, SHEETS, "monolith_gen"], cwd=design, env=env)
    kicad(["sch", "export", "netlist", "--format", "kicadsexpr", "-o", "monolith_gen.net", "monolith_gen.kicad_sch"])
    kicad(["sch", "export", "pdf", "-o", "sheets.pdf", "monolith_gen.kicad_sch"])
    run([PY, os.path.join(W, "tools", "netlist_truth.py"), os.path.join(SHEETS, "monolith_gen.net"),
         os.path.join(SHEETS, "monolith_gen.kicad.json")])
    # the drawn sheets must equal the circuit
    run([PY, os.path.join(W, "tools", "compare.py"), os.path.join(SH, "frozen_netlist.json"),
         os.path.join(SHEETS, "monolith_gen.kicad.json")], tail=3)
    pdf = os.path.join(RENDER, "sheets.pdf")
    shutil.move(os.path.join(SHEETS, "sheets.pdf"), pdf)
    render(pdf)
    print("NETLIST OK. Renders: out/render/page-*.png (page 1 is the root sheet; 2 3V3 rail, 3 cells and gauge, "
          "4 MCU, 5-6 USB ports)")

if __name__ == "__main__":
    main()
